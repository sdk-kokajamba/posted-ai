"""Post model."""

from dataclasses import MISSING, dataclass, field, fields
from enum import StrEnum
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Enum,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    false,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from bot.db.base import Base, TimestampMixin

# BigInteger for PostgreSQL, INTEGER for SQLite (need for AUTOINCREMENT)
BigIntPK = BigInteger().with_variant(Integer, "sqlite")


class PostStatus(StrEnum):
    ACT = "act"
    ARCH = "arch"
    PUB = "pub"
    MODER = "moder"
    AP_PUB = "ap_pub"


class ContentType(StrEnum):
    TEXT = "text"
    PHOTO = "photo"
    VIDEO = "video"


def _enum_values(enum_cls: type[StrEnum]) -> list[str]:
    """Return the DB values for ``enum_cls``.

    ``sa.Enum`` stores member *names* by default (``"TEXT"``, ``"PUB"``);
    the CHECK constraint and everything else here assume *values*
    (``"text"``, ``"pub"``), so opt in explicitly.
    """
    return [member.value for member in enum_cls]


class Post(TimestampMixin, Base):
    """Posts scheduled for publication in a channel."""

    __tablename__ = "posts"
    __table_args__ = (
        # Referenced by potential future composite FKs (e.g. AutoPostPrompt).
        UniqueConstraint("id", "user_id", name="uq_posts_id_user"),
        # Composite FK enforces "post belongs to a channel owned by the same user"
        # at the database level (target: uq_channels_id_user on ``channels``).
        ForeignKeyConstraint(
            ["channel_id", "user_id"],
            ["channels.id", "channels.user_id"],
            ondelete="CASCADE",
            name="fk_posts_channel_owner",
        ),
        CheckConstraint(
            "(content_type = 'text' AND text IS NOT NULL AND text <> '') OR "
            "(content_type IN ('photo', 'video') "
            "AND media_id IS NOT NULL AND media_id <> '')",
            name="content_matches_type",
        ),
        # Listings by status, ordered by publication date.
        Index(
            "ix_posts_user_status_pubdate",
            "user_id",
            "status",
            text("pub_date DESC"),
        ),
        # Cleanup of stale moderation rows.
        Index("ix_posts_user_status_created", "user_id", "status", "created_at"),
        # Future per-channel listings.
        Index("ix_posts_channel_status_pubdate", "channel_id", "status", "pub_date"),
    )

    # Internal surrogate primary key, generated by the database.
    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True, autoincrement=True)

    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    channel_id: Mapped[int] = mapped_column(nullable=False)
    status: Mapped[PostStatus] = mapped_column(
        Enum(
            PostStatus,
            native_enum=False,
            length=16,
            values_callable=_enum_values,
        ),
        nullable=False,
        default=PostStatus.MODER,
        server_default=PostStatus.MODER.value,
    )
    content_type: Mapped[ContentType] = mapped_column(
        Enum(
            ContentType,
            native_enum=False,
            length=16,
            values_callable=_enum_values,
        ),
        nullable=False,
        default=ContentType.TEXT,
        server_default=ContentType.TEXT.value,
    )
    theme: Mapped[str] = mapped_column(String(255), nullable=False)
    text: Mapped[str | None] = mapped_column(Text, nullable=True)
    text_html: Mapped[str | None] = mapped_column(Text, nullable=True)
    media_id: Mapped[str | None] = mapped_column(String(255), nullable=True)
    # Unix-timestamp; a missing value means the post is not yet scheduled.
    pub_date: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    msg_id: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    spoiler: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        server_default=false(),
    )
    # Auto-delete delay in hours.
    msg_delete: Mapped[int | None] = mapped_column(Integer, nullable=True)

    def __repr__(self) -> str:
        return f"Post(id={self.id}, status={self.status.value!r}, theme={self.theme!r})"


@dataclass(frozen=True, kw_only=True, slots=True)
class PostCreateData:
    user_id: int
    channel_id: int
    theme: str
    content_type: ContentType = ContentType.TEXT
    text: str | None = None
    text_html: str | None = None
    media_id: str | None = None
    pub_date: int | None = None
    spoiler: bool = False
    msg_delete: int | None = None
    status: PostStatus = PostStatus.MODER


@dataclass(frozen=True, kw_only=True, slots=True)
class PostUpdateData:
    """Partial update payload.

    Fields that were not supplied by the caller default to :data:`MISSING`
    and are skipped by :meth:`to_changes`. Passing ``field=None`` explicitly
    clears the column (only valid for nullable fields).
    """

    # ``field(default_factory=lambda: MISSING)`` — using ``MISSING`` directly
    # as a class-body default marks the field as *required* in ``__init__``
    # (dataclasses treats ``default is MISSING`` as "no default"), which would
    # break the "field absent = don't change" contract.
    channel_id: int | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    status: PostStatus | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    content_type: ContentType | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    theme: str | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    text: str | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    text_html: str | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    media_id: str | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    pub_date: int | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    msg_id: int | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    spoiler: bool | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    msg_delete: int | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]

    def to_changes(self) -> dict[str, Any]:
        """Return only the fields explicitly set on this instance."""
        return {
            f.name: getattr(self, f.name)
            for f in fields(self)
            if getattr(self, f.name) is not MISSING
        }
