"""AutoPrompt model."""

from dataclasses import dataclass
from enum import IntEnum
from typing import ClassVar

from sqlalchemy import (
    CheckConstraint,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    SmallInteger,
    String,
    Text,
)
from sqlalchemy.orm import Mapped, mapped_column

from bot.db.base import Base, BigIntPK, TimestampMixin
from bot.db.updates import UNSET, UnsetType, UpdateDataBase


class Weekday(IntEnum):
    """ISO weekday — matches ``datetime.weekday()`` (Mon=0 … Sun=6)."""

    MON = 0
    TUE = 1
    WED = 2
    THU = 3
    FRI = 4
    SAT = 5
    SUN = 6


# Sanity constants — used in CheckConstraints and Schedule helpers.
MINUTES_PER_DAY = 24 * 60  # 1440
ALL_WEEKDAYS_MASK = (1 << 7) - 1  # 0b1111111 == 127


class AutoPrompt(TimestampMixin, Base):
    """Prompts attached to auto posts owned by users."""

    __tablename__ = "autoprompts"
    __table_args__ = (
        # Composite FK: an auto prompt belongs to an auto post owned by the
        # same user (target: uq_autoposts_id_user on ``autoposts``). CASCADE,
        # not SET NULL — with a composite FK, SET NULL would null out
        # `user_id` (NOT NULL) along with `autopost_id`, which PostgreSQL
        # rejects.
        ForeignKeyConstraint(
            ["autopost_id", "user_id"],
            ["autoposts.id", "autoposts.user_id"],
            ondelete="CASCADE",
            name="fk_autoprompts_autopost_owner",
        ),
        # Listings filtered by user + autopost (get_page, get_preview).
        Index(
            "ix_autoprompts_user_autopost",
            "user_id",
            "autopost_id",
        ),
        # Lookups keyed by autopost only (count_for_autopost).
        Index("ix_autoprompts_autopost", "autopost_id"),
        # ---- schedule validation -------------------------------------------
        # bitmask in [1, 127]: at least one weekday selected, no unknown bits.
        CheckConstraint(
            "day_mask IS NULL OR (day_mask > 0 AND day_mask <= 127)",
            name="day_mask_range",
        ),
        # minutes from midnight in [0, 1439].
        CheckConstraint(
            "time_start_min IS NULL OR (time_start_min >= 0 AND time_start_min < 1440)",
            name="time_start_range",
        ),
        CheckConstraint(
            "time_end_min IS NULL OR (time_end_min >= 0 AND time_end_min < 1440)",
            name="time_end_range",
        ),
        # end without start is meaningless.
        CheckConstraint(
            "time_end_min IS NULL OR time_start_min IS NOT NULL",
            name="time_end_requires_start",
        ),
        # start == end is ambiguous (zero-length vs full-day) — reject it.
        CheckConstraint(
            "time_end_min IS NULL OR time_start_min IS NULL OR time_end_min <> time_start_min",
            name="time_end_differs_from_start",
        ),
    )

    # Internal surrogate primary key, generated by the database.
    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True, autoincrement=True)

    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )
    # FK to ``autoposts`` is declared only via the composite
    # ForeignKeyConstraint above.
    autopost_id: Mapped[int] = mapped_column(nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    tags: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # ---- schedule ----------------------------------------------------------
    # Days of week as a bitmask: bit 0 = Monday, bit 6 = Sunday.
    # ``None`` = no day constraint (publish any day).
    # ``day_mask & (1 << weekday)`` is non-zero on an active day.
    day_mask: Mapped[int | None] = mapped_column(SmallInteger, nullable=True)

    # Publication time window, in minutes from midnight (0..1439).
    # Semantics:
    #   start=None, end=None          → any time
    #   start=X,    end=None          → exactly at X
    #   start=X,    end=Y, X <  Y     → [X, Y] inclusive (same day)
    #   start=X,    end=Y, X >  Y     → [X, 1440) ∪ [0, Y] (overnight window)
    time_start_min: Mapped[int | None] = mapped_column(SmallInteger, nullable=True)
    time_end_min: Mapped[int | None] = mapped_column(SmallInteger, nullable=True)

    def __repr__(self) -> str:
        return (
            f"AutoPrompt(id={self.id}, autopost_id={self.autopost_id}, "
            f"day_mask={self.day_mask!r}, "
            f"time={self.time_start_min!r}-{self.time_end_min!r})"
        )


@dataclass(frozen=True, kw_only=True, slots=True)
class AutoPromptCreateData:
    user_id: int
    autopost_id: int
    text: str
    tags: str | None = None
    day_mask: int | None = None
    time_start_min: int | None = None
    time_end_min: int | None = None


@dataclass(frozen=True, kw_only=True, slots=True)
class AutoPromptUpdateData(UpdateDataBase):
    """Partial update payload for auto-prompt records.

    Fields that were not supplied by the caller default to :data:`UNSET`
    — "leave the column untouched" — and are skipped by :meth:`to_changes`.
    Passing ``field=None`` explicitly clears the column (only valid for
    nullable fields; non-nullable ones raise :class:`UpdateDataValidationError`).

    All schedule fields are nullable; passing ``None`` explicitly clears
    them. Use :class:`~bot.db.schedule.Schedule` to convert user input.
    """

    autopost_id: int | UnsetType = UNSET
    text: str | UnsetType = UNSET

    tags: str | UnsetType | None = UNSET
    day_mask: int | UnsetType | None = UNSET
    time_start_min: int | UnsetType | None = UNSET
    time_end_min: int | UnsetType | None = UNSET

    not_null_fields: ClassVar[frozenset[str]] = frozenset({"autopost_id", "text"})
