"""AutoPrompt model."""

from dataclasses import dataclass
from enum import StrEnum

from sqlalchemy import (
    BigInteger,
    Boolean,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    String,
    Text,
    false,
)
from sqlalchemy.orm import Mapped, mapped_column

from bot.db.base import Base, TimestampMixin
from bot.db.enums import enum_column
from bot.db.updates import UNSET, UnsetType, UpdateDataBase


class AutoPromptStatus(StrEnum):
    ACT = "act"
    ARCH = "arch"
    MODER = "moder"


# BigInteger for PostgreSQL, INTEGER for SQLite (need for AUTOINCREMENT)
BigIntPK = BigInteger().with_variant(Integer, "sqlite")


class AutoPrompt(TimestampMixin, Base):
    """Prompts attached to auto posts owned by users."""

    __tablename__ = "autoprompts"
    __table_args__ = (
        # Composite FK: an auto prompt belongs to an auto post owned by the
        # same user (target: uq_autoposts_id_user on ``autoposts``). CASCADE,
        # not SET NULL — with a composite FK, SET NULL would null out
        # ``user_id`` (NOT NULL) along with ``autopost_id``, which PostgreSQL
        # rejects.
        ForeignKeyConstraint(
            ["autopost_id", "user_id"],
            ["autoposts.id", "autoposts.user_id"],
            ondelete="CASCADE",
            name="fk_autoprompts_autopost_owner",
        ),
        # Listings filtered by user + autopost + status (get_page, get_preview).
        Index(
            "ix_autoprompts_user_autopost_status",
            "user_id",
            "autopost_id",
            "status",
        ),
        # Lookups and bulk operations keyed by autopost only
        # (list_ids_for_autopost, update_status_for_autopost, cleanup).
        Index("ix_autoprompts_autopost", "autopost_id"),
    )

    # Internal surrogate primary key, generated by the database.
    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True, autoincrement=True)

    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    # FK to ``autoposts`` is declared only via the composite
    # ForeignKeyConstraint above.
    autopost_id: Mapped[int] = mapped_column(nullable=False)
    status: Mapped[AutoPromptStatus] = mapped_column(
        enum_column(AutoPromptStatus),
        nullable=False,
        default=AutoPromptStatus.MODER,
        server_default=AutoPromptStatus.MODER.value,
    )
    req_moder: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        server_default=false(),
    )
    prompt_text: Mapped[str] = mapped_column(Text, nullable=False)
    tags: Mapped[str | None] = mapped_column(String(255), nullable=True)
    day_pub: Mapped[str | None] = mapped_column(String(32), nullable=True)
    time_pub: Mapped[str | None] = mapped_column(String(32), nullable=True)

    def __repr__(self) -> str:
        return (
            f"AutoPrompt(id={self.id}, autopost_id={self.autopost_id}, "
            f"status={self.status.value!r})"
        )


@dataclass(frozen=True, kw_only=True, slots=True)
class AutoPromptCreateData:
    user_id: int
    autopost_id: int
    prompt_text: str
    status: AutoPromptStatus = AutoPromptStatus.MODER
    req_moder: bool = False
    tags: str | None = None
    day_pub: str | None = None
    time_pub: str | None = None


@dataclass(frozen=True, kw_only=True, slots=True)
class AutoPromptUpdateData(UpdateDataBase):
    """Partial update payload for auto-prompt records.

    Fields that were not supplied by the caller default to :data:`UNSET`
    — "leave the column untouched" — and are skipped by :meth:`to_changes`.
    Passing ``field=None`` explicitly clears the column (only valid for
    nullable fields; non-nullable ones raise :class:`UpdateDataValidationError`).
    """

    autopost_id: int | UnsetType = UNSET
    status: AutoPromptStatus | UnsetType = UNSET
    req_moder: bool | UnsetType = UNSET
    prompt_text: str | UnsetType = UNSET

    tags: str | UnsetType = UNSET
    day_pub: str | UnsetType = UNSET
    time_pub: str | UnsetType = UNSET

    not_null_fields: frozenset[str] = frozenset(
        {"autopost_id", "status", "req_moder", "prompt_text"}
    )
