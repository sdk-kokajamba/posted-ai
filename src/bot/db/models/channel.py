"""Channel model."""

from dataclasses import dataclass

from sqlalchemy import BigInteger, ForeignKey, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from bot.db.base import Base, BigIntPK, TimestampMixin


class Channel(TimestampMixin, Base):
    """Telegram channels added by users."""

    __tablename__ = "channels"
    __table_args__ = (
        UniqueConstraint("user_id", "name", name="uq_channels_user_name"),
        # Target for the composite FK from ``posts``; lets the database enforce
        # that a post can only reference a channel owned by the same user.
        UniqueConstraint("id", "user_id", name="uq_channels_id_user"),
    )

    # Internal surrogate primary key, generated by the database.
    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True, autoincrement=True)

    # External Telegram channel ID; comes from Telegram, never generated by us.
    #
    # UNIQUE on purpose: a Telegram channel can belong to exactly one user
    # of this bot. If the same channel is added by a second user, we reject
    # it at the DB level (``ChannelAlreadyExistsError`` in the repository),
    # instead of silently creating a duplicate that would later break
    # posting / moderation. The composite FK from ``posts`` / ``autoposts``
    # (``channel_id, user_id``) additionally pins the "channel belongs to
    # this user" invariant — but that one is per-user, while this UNIQUE
    # is global.
    tg_id: Mapped[int] = mapped_column(BigInteger, unique=True)
    name: Mapped[str] = mapped_column(String(128))
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))

    def __repr__(self) -> str:
        return f"Channel(id={self.id}, name={self.name!r})"


@dataclass(frozen=True, kw_only=True, slots=True)
class ChannelCreateData:
    user_id: int
    tg_id: int
    name: str
