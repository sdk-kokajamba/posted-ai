"""AutoPost model."""

from dataclasses import MISSING, dataclass, field, fields
from enum import StrEnum
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    String,
    UniqueConstraint,
    false,
)
from sqlalchemy.orm import Mapped, mapped_column

from bot.db.base import Base, TimestampMixin
from bot.db.enums import enum_column


class AutoPostStatus(StrEnum):
    ACT = "act"
    ARCH = "arch"
    MODER = "moder"


# BigInteger for PostgreSQL, INTEGER for SQLite (need for AUTOINCREMENT)
BigIntPK = BigInteger().with_variant(Integer, "sqlite")


class AutoPost(TimestampMixin, Base):
    """Auto-posting templates owned by users."""

    __tablename__ = "autoposts"
    __table_args__ = (
        # Template names are unique per user.
        UniqueConstraint("user_id", "name", name="uq_autoposts_user_name"),
        # Target for the composite FK from the ``autopost_prompts``
        UniqueConstraint("id", "user_id", name="uq_autoposts_id_user"),
        # Composite FK enforces "auto post belongs to a channel owned by the
        # same user" at the database level.
        ForeignKeyConstraint(
            ["channel_id", "user_id"],
            ["channels.id", "channels.user_id"],
            ondelete="CASCADE",
            name="fk_autoposts_channel_owner",
        ),
        # Listings by status per user.
        Index("ix_autoposts_user_status", "user_id", "status"),
        # Listings filtered by channel + status
        Index(
            "ix_autoposts_user_channel_status",
            "user_id",
            "channel_id",
            "status",
        ),
    )

    # Internal surrogate primary key, generated by the database.
    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True, autoincrement=True)

    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    # FK is declared only via the composite ForeignKeyConstraint above.
    channel_id: Mapped[int] = mapped_column(nullable=False)
    status: Mapped[AutoPostStatus] = mapped_column(
        enum_column(AutoPostStatus),
        nullable=False,
        default=AutoPostStatus.MODER,
        server_default=AutoPostStatus.MODER.value,
    )
    name: Mapped[str] = mapped_column(String(128), nullable=False)
    require_moderation: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        server_default=false(),
    )

    def __repr__(self) -> str:
        return f"AutoPost(id={self.id}, name={self.name!r}, status={self.status.value!r})"


@dataclass(frozen=True, kw_only=True, slots=True)
class AutoPostCreateData:
    user_id: int
    channel_id: int
    name: str
    require_moderation: bool = False
    status: AutoPostStatus = AutoPostStatus.MODER


@dataclass(frozen=True, kw_only=True, slots=True)
class AutoPostUpdateData:
    """Partial update payload.

    Fields that were not supplied by the caller default to :data:`MISSING`
    and are skipped by :meth:`to_changes`. Passing ``field=None`` explicitly
    clears the column (only valid for nullable fields).
    """

    channel_id: int | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    name: str | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    status: AutoPostStatus | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]
    require_moderation: bool | None = field(default_factory=lambda: MISSING)  # type: ignore[assignment]

    def to_changes(self) -> dict[str, Any]:
        """Return only the fields explicitly set on this instance."""
        return {
            f.name: getattr(self, f.name)
            for f in fields(self)
            if getattr(self, f.name) is not MISSING
        }
